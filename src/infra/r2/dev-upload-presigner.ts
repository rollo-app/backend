import type { Presigner } from "./presigner";

export const DEV_UPLOAD_PREFIX = "/dev/upload/";

/**
 * Development only (`DEV_LOCAL_UPLOADS=1`): the "presigned" URL points at the worker itself (`PUT /dev/upload/<key>`,
 * using the request's `origin`, so the phone reaches it via the network IP), signed with an HMAC.
 * The route in `src/index.ts` checks the signature with `verify` and writes through the storage.
 */
export class DevUploadPresigner implements Presigner {
  constructor(private readonly secret: string) {}

  async putUrl(key: string, { origin, size, expiresIn }: { origin: string; size: number | null; expiresIn: number }): Promise<string> {
    const exp = Date.now() + expiresIn * 1000;
    const url = new URL(`${DEV_UPLOAD_PREFIX}${key}`, origin);
    url.searchParams.set("exp", String(exp));
    if (size != null) url.searchParams.set("size", String(size));
    url.searchParams.set("sig", await this.signature(key, exp, size));
    return url.toString();
  }

  /** A placeholder that is never used. */
  async getUrl(key: string): Promise<string> {
    return `https://dev.invalid/${key}`;
  }

  private async signature(key: string, exp: number, size?: number | null): Promise<string> {
    const hmacKey = await crypto.subtle.importKey("raw", new TextEncoder().encode(this.secret), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
    const sig = await crypto.subtle.sign("HMAC", hmacKey, new TextEncoder().encode(size != null ? `${key}\n${exp}\n${size}` : `${key}\n${exp}`));
    return [...new Uint8Array(sig)].map((b) => b.toString(16).padStart(2, "0")).join("");
  }

  /** Validates a local upload URL generated by `putUrl`. Returns the signed size (null: unlimited) or false. */
  async verify(
    key: string,
    exp: string | undefined,
    sig: string | undefined,
    size?: string | undefined,
  ): Promise<{ size: number | null } | false> {
    const expMs = Number(exp);
    if (!sig || !Number.isFinite(expMs) || expMs < Date.now()) return false;
    const sizeBytes = size === undefined ? null : Number(size);
    if (sizeBytes !== null && !Number.isInteger(sizeBytes)) return false;
    return sig === (await this.signature(key, expMs, sizeBytes)) ? { size: sizeBytes } : false;
  }
}
