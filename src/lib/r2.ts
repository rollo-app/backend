import { AwsClient } from "aws4fetch";
import { HTTPException } from "hono/http-exception";
import type { Env, MediaType } from "../types";
import { InvalidJpegError, stripJpegMetadata } from "./strip-jpeg-metadata";

export const DEV_UPLOAD_PREFIX = "/dev/upload/";

export const devUploadsEnabled = (env: Env) => env.DEV_LOCAL_UPLOADS === "1";

/**
 * Presigned URL (R2's S3 API) so the phone uploads straight to the bucket,
 * without the file going through the Worker.
 *
 * In `wrangler dev` with DEV_LOCAL_UPLOADS=1 the URL points at the worker itself (using the
 * request's `origin`, so the phone reaches it via the network IP) and ends up in the local R2.
 *
 * With `size` the URL only accepts a PUT of exactly that many bytes (`content-length` is a signed header on R2;
 * the dev route checks the body length). Without it (legacy pending rows) the size is not limited.
 */
export async function presignPut(
  env: Env,
  key: string,
  origin: string,
  size?: number | null,
  expiresIn = 900,
): Promise<string> {
  if (devUploadsEnabled(env)) {
    const exp = Date.now() + expiresIn * 1000;
    const url = new URL(`${DEV_UPLOAD_PREFIX}${key}`, origin);
    url.searchParams.set("exp", String(exp));
    if (size != null) url.searchParams.set("size", String(size));
    url.searchParams.set("sig", await devSignature(env, key, exp, size));
    return url.toString();
  }

  const client = new AwsClient({
    accessKeyId: env.R2_ACCESS_KEY_ID,
    secretAccessKey: env.R2_SECRET_ACCESS_KEY,
    service: "s3",
    region: "auto",
  });
  const url = new URL(
    `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com/${env.R2_BUCKET_NAME}/${key}`,
  );
  url.searchParams.set("X-Amz-Expires", String(expiresIn));
  // aws4fetch leaves content-length out of the signature by default; `allHeaders` signs it, so R2 rejects
  // a PUT whose Content-Length differs.
  const headers = size != null ? { "content-length": String(size) } : undefined;
  const signed = await client.sign(new Request(url, { method: "PUT", headers }), {
    aws: { signQuery: true, allHeaders: size != null },
  });
  return signed.url;
}

/** Presigned GET URL for a stored file (e.g. a link in a support email). With DEV_LOCAL_UPLOADS it is a placeholder that is never used. */
export async function presignGet(env: Env, key: string, expiresIn = 7 * 24 * 3600): Promise<string> {
  if (devUploadsEnabled(env)) return `https://dev.invalid/${key}`;
  const client = new AwsClient({
    accessKeyId: env.R2_ACCESS_KEY_ID,
    secretAccessKey: env.R2_SECRET_ACCESS_KEY,
    service: "s3",
    region: "auto",
  });
  const url = new URL(`https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com/${env.R2_BUCKET_NAME}/${key}`);
  url.searchParams.set("X-Amz-Expires", String(expiresIn));
  const signed = await client.sign(new Request(url, { method: "GET" }), { aws: { signQuery: true } });
  return signed.url;
}

export function mediaKeys(tripId: string, mediaId: string, type: MediaType) {
  const base = `trips/${tripId}/${mediaId}`;
  return {
    original: `${base}/original.${type === "video" ? "mp4" : "jpg"}`,
    thumb: `${base}/thumb.jpg`,
    /** 2048 px compressed JPEG of a photo, kept forever (the original is deleted 30 days after the reveal). */
    display: `${base}/display.jpg`,
  };
}

async function devSignature(env: Env, key: string, exp: number, size?: number | null): Promise<string> {
  const hmacKey = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(env.R2_SECRET_ACCESS_KEY),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const sig = await crypto.subtle.sign("HMAC", hmacKey, new TextEncoder().encode(size != null ? `${key}\n${exp}\n${size}` : `${key}\n${exp}`));
  return [...new Uint8Array(sig)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** Validates a local upload URL generated by `presignPut`. Returns the signed size (null: unlimited) or false. */
export async function verifyDevUpload(
  env: Env,
  key: string,
  exp: string | undefined,
  sig: string | undefined,
  size?: string | undefined,
): Promise<{ size: number | null } | false> {
  const expMs = Number(exp);
  if (!sig || !Number.isFinite(expMs) || expMs < Date.now()) return false;
  const sizeBytes = size === undefined ? null : Number(size);
  if (sizeBytes !== null && !Number.isInteger(sizeBytes)) return false;
  return sig === (await devSignature(env, key, expMs, sizeBytes)) ? { size: sizeBytes } : false;
}

type ByteRange = { start: number; end?: number } | { suffix: number };

/**
 * Parses a single `bytes=` range (RFC 9110). Returns null for anything we don't honor (missing, malformed,
 * another unit or several ranges): those requests get the whole file with 200, which the RFC allows.
 */
export function parseByteRange(header: string | null): ByteRange | null {
  const match = header?.trim().match(/^bytes=(\d*)-(\d*)$/);
  if (!match) return null;
  const [, first, last] = match;
  if (first === "") return last === "" ? null : { suffix: Number(last) };
  const start = Number(first);
  if (last === "") return { start };
  const end = Number(last);
  return end < start ? null : { start, end };
}

/** Resolves a parsed range against the object size: inclusive offsets, or null if unsatisfiable (416). */
function resolveRange(range: ByteRange, size: number): { start: number; end: number } | null {
  if ("suffix" in range) {
    if (range.suffix === 0 || size === 0) return null;
    return { start: Math.max(0, size - range.suffix), end: size - 1 };
  }
  if (range.start >= size) return null;
  return { start: range.start, end: Math.min(range.end ?? size - 1, size - 1) };
}

function mediaHeaders(object: R2Object): Headers {
  const headers = new Headers();
  object.writeHttpMetadata(headers);
  if (!headers.has("content-type")) {
    headers.set("content-type", object.key.endsWith(".mp4") ? "video/mp4" : "image/jpeg");
  }
  headers.set("etag", object.httpEtag);
  headers.set("cache-control", "private, max-age=31536000, immutable");
  headers.set("accept-ranges", "bytes");
  return headers;
}

/**
 * Streams a media file from R2 with long private caching (keys never change content).
 * With `fallbackKey`, a missing object is replaced by that one (e.g. the display file standing in for a purged original).
 * Throws 404 if neither exists.
 *
 * Honors a single `Range` (206 / 416): iOS AVPlayer probes videos with `bytes=0-1` and refuses to play if it gets
 * the whole file back, and Cloudflare does not add range support to responses a Worker builds itself.
 * `If-Range` only matches the exact etag; anything else (e.g. a date) falls back to the whole file.
 */
export async function serveMediaFile(
  bucket: R2Bucket,
  key: string,
  fallbackKey?: string | null,
  requestHeaders?: Headers,
): Promise<Response> {
  const notFound = () => new HTTPException(404, { message: "Archivo no encontrado" });
  const range = parseByteRange(requestHeaders?.get("range") ?? null);

  if (range) {
    // The size is needed to resolve the range, so look the object up first (only when a range was asked for).
    const head = (await bucket.head(key)) ?? (fallbackKey ? await bucket.head(fallbackKey) : null);
    if (!head) throw notFound();
    const ifRange = requestHeaders?.get("if-range");
    if (!ifRange || ifRange === head.httpEtag) {
      const bounds = resolveRange(range, head.size);
      if (!bounds) {
        const headers = mediaHeaders(head);
        headers.set("content-range", `bytes */${head.size}`);
        return new Response(null, { status: 416, headers });
      }
      const length = bounds.end - bounds.start + 1;
      const object = await bucket.get(head.key, { range: { offset: bounds.start, length } });
      if (!object) throw notFound();
      const headers = mediaHeaders(object);
      headers.set("content-range", `bytes ${bounds.start}-${bounds.end}/${object.size}`);
      headers.set("content-length", String(length));
      return new Response(object.body, { status: 206, headers });
    }
  }

  const object = (await bucket.get(key)) ?? (fallbackKey ? await bucket.get(fallbackKey) : null);
  if (!object) throw notFound();
  const headers = mediaHeaders(object);
  headers.set("content-length", String(object.size));
  return new Response(object.body, { headers });
}

/**
 * Like serveMediaFile, but for files that leave under a profile's permission (featured photos): the JPEG is
 * buffered and served without metadata (EXIF GPS/date/caption/author, XMP, comments). Fails closed: anything
 * that isn't a well-formed JPEG is a 404, never the stored bytes.
 */
export async function serveStrippedJpeg(bucket: R2Bucket, key: string, fallbackKey?: string | null): Promise<Response> {
  const notFound = () => new HTTPException(404, { message: "Archivo no encontrado" });
  const object = (await bucket.get(key)) ?? (fallbackKey ? await bucket.get(fallbackKey) : null);
  if (!object) throw notFound();
  key = object.key;
  const contentType = object.httpMetadata?.contentType;
  if (key.endsWith(".mp4") || (contentType && contentType !== "image/jpeg")) throw notFound();

  let bytes: Uint8Array;
  try {
    bytes = stripJpegMetadata(new Uint8Array(await object.arrayBuffer()));
  } catch (err) {
    if (err instanceof InvalidJpegError) throw notFound();
    throw err;
  }

  return new Response(bytes, {
    headers: {
      "content-type": "image/jpeg",
      "content-length": String(bytes.length),
      // Stripping is deterministic, so the stored object's etag plus a suffix identifies these bytes.
      etag: `"${object.etag}-stripped"`,
      "cache-control": "private, max-age=31536000, immutable",
    },
  });
}
